import type { PassiveBonus, PassiveControl, Layout } from './passives.ts'
import { controlBonus, controlMax, fromLayout, fallback } from './passives.ts'
import { LEGENDARY_PET_DATA, type LegendaryPool } from '../data/legendaryPets.generated.ts'
import type { GeneratedEffect } from '../data/passives.generated.ts'

// Relative imports only: the share-link codec (and so the Worker) use this.

/**
 * Once a pet/mount is legendary, the player crafts one specific "Croquette
 * infusée" (one of 8 per family) and feeds it — that croquette always
 * grants the same fixed bonus; a later one replaces it. This is the planner
 * picking the same thing, same as picking a rune the piece already carries.
 *
 * Which family each croquette belongs to and the bearer's own stat effects
 * (value, sign, stack cap) come from scripts/fetch-legendary-pets.ts, same
 * game data and the same extraction fetch-passives.ts already uses for item
 * passives — regenerated by the hourly update-data workflow, so a rebalance
 * (a percentage, a stack cap) reaches the app with no code change. Only two
 * things below are still hand-kept and need a look when a new slug shows up
 * in that generated file: LEGENDARY_LAYOUT (grouping effects into one
 * control, same convention as passives.ts's own LAYOUT) and LEGENDARY_SUPPRESS
 * (bonuses whose effect is only half the real tradeoff — a shield, a heal,
 * an ally buff — where a flat number would misrepresent it). Display name
 * and text (petleg_<slug>_name/_text) stay hand-translated in the 4 locale
 * files: the game doesn't expose them under a stable key to fetch.
 */
export type { LegendaryPool }
export const LEGENDARY_POOLS: LegendaryPool[] = ['bakushana', 'poukachi', 'kwakarticho', 'magicrabe']

export type LegendaryBonus = {
  id:   string
  pool: LegendaryPool
  nameKey: string
  textKey: string
  /** Present when (part of) the effect adds to the bearer's own modeled stats. */
  control?: PassiveControl
}

// Raw effects that need grouping into one control instead of the generic
// one-control-per-effect fallback: two alternatives merged into one choice,
// two stats combined into one option, or a duplicate "grade" of the same
// effect (game data quirk) deduped down to one. Keyed by the generated
// file's slug.
const LEGENDARY_LAYOUT: Record<string, Layout[]> = {
  bwork:             [{ options: [['meleeDamagePercent'], ['rangedDamagePercent']] }], // adjacent to an enemy / not
  strich:            [{ options: [['lock'], ['dodge']] }],                             // pushed / attracted
  kozaru:            [{ options: [['lock', 'dodge']] }],                               // push/attract/transpose: both together
  leopena:           [{ options: [['ap']] }],                                          // dedupe the grade-3 repeat
  thoronduddleswell: [{ options: [['mp']] }],                                          // dedupe the grade-3 repeat
  bambooto:          [{ options: [['range']] }],                                       // dedupe the grade-3 repeat
}

// These do touch the bearer's own stats in the raw data, but only one side
// of a tradeoff this planner can't track the other half of (a shield, a
// heal, "while N enemies are adjacent") — flattening just that one number
// would misrepresent the bonus, so they stay text only.
const LEGENDARY_SUPPRESS = new Set([
  'moskito',    // sacrifices final damage to heal — the heal isn't modeled, showing only the loss would mislead
  'sauroshell', // a shield sized to allies' levels, at the cost of resistance on their death
  'crackler',   // resistance traded with allies, returned on their death
  'wabbit',     // swings with the enemy count and their deaths during the fight
  'trool',      // same
  'kitsou',     // dodge scales with nearby enemies, not a flat amount
  'arachnee',   // lock scales with nearby enemies, not a flat amount
  'bwak',       // the generated data only has the bearer's own sacrifice, not the ally gain it's traded for
])

/** Flags a slug whose hand layout no longer matches the generated effects
 * (the game data changed shape) — falls back to one control per effect. */
export const LEGENDARY_LAYOUT_MISMATCHES: string[] = []

function buildControl(id: string, slug: string, effects: GeneratedEffect[]): PassiveControl | undefined {
  if (LEGENDARY_SUPPRESS.has(slug)) return undefined
  const layout = LEGENDARY_LAYOUT[slug]
  let controls = layout ? fromLayout(0, effects, layout) : fallback(0, effects)
  if (layout && !controls) { LEGENDARY_LAYOUT_MISMATCHES.push(slug); controls = fallback(0, effects) }
  if (!controls || controls.length === 0) return undefined
  return { ...controls[0], id }
}

export const LEGENDARY_BONUSES: LegendaryBonus[] = Object.entries(LEGENDARY_PET_DATA)
  .map(([slug, source]) => {
    const id = `${source.pool}.${slug}`
    return {
      id, pool: source.pool, nameKey: `petleg_${slug}_name`, textKey: `petleg_${slug}_text`,
      control: buildControl(id, slug, source.effects),
    }
  })
  .sort((a, b) => a.id.localeCompare(b.id))

const BY_ID = new Map(LEGENDARY_BONUSES.map(b => [b.id, b]))

export const legendaryBonusOf = (id: string): LegendaryBonus | undefined => BY_ID.get(id)

/** Highest value its control takes (stacks, or option count); 1 for a text-only bonus (plain on/off). */
export function legendaryMax(id: string): number {
  const b = BY_ID.get(id)
  return b?.control ? controlMax(b.control) : 1
}

/** The picked bonus's value on the bearer's own stats; {} when text-only or unset. */
export function legendaryStatBonus(pick: { id: string; value: number } | null): PassiveBonus {
  if (!pick) return {}
  const b = BY_ID.get(pick.id)
  return b?.control ? controlBonus(b.control, pick.value) : {}
}

/** A saved pick kept in range for its bonus (unknown id or a value past its max is dropped/clamped). */
export function sanitizeLegendaryPick(raw: unknown): { id: string; value: number } | null {
  if (raw == null || typeof raw !== 'object' || Array.isArray(raw)) return null
  const { id, value } = raw as Record<string, unknown>
  if (typeof id !== 'string') return null
  const bonus = BY_ID.get(id)
  if (!bonus) return null
  const max = legendaryMax(id)
  const n = typeof value === 'number' && Number.isFinite(value) ? Math.trunc(value) : 1
  return { id, value: Math.min(max, Math.max(bonus.control ? 0 : 1, n)) }
}
